"""Regenerate browser reference data using the installed Python package."""
import itertools
import json
import random
import warnings
from dataclasses import asdict
from pathlib import Path

from Bio import BiopythonWarning
from Bio.Data import CodonTable, IUPACData
from Bio.SeqUtils.MeltingTemp import DNA_NN3

from dna_sequence_analyzer.fasta import read_fasta_text
from dna_sequence_analyzer.gc import analyze_records
from dna_sequence_analyzer.orfs import find_orfs
from dna_sequence_analyzer.tm import MeltingConditions, melting_record_for_sequence
from dna_sequence_analyzer.translate import TABLES, transcribe, translate_frames
from dna_sequence_analyzer.windows import gc_windows_for_records, skew_windows_for_records

ROOT = Path(__file__).resolve().parents[1]


def reference(sequence):
    frames = {table: [asdict(row) for row in translate_frames(sequence, table)] for table in TABLES}
    options = [
        {},
        {"alternative_starts": True, "include_nested": True, "allow_no_stop": True},
        {"table": 2, "min_aa": 2, "alternative_starts": True, "allow_no_stop": True},
    ]
    conditions = [{"saltcorr": method, "mg_mM": 1.5, "dntps_mM": 0.25, "k_mM": 20}
                  for method in range(8)]
    conditions += [{}, {"selfcomp": True, "na_mM": 0, "mg_mM": 2, "saltcorr": 7},
                   {"mg_mM": 0.2, "dntps_mM": 1, "saltcorr": 7}]
    return {
        "rna": transcribe(sequence),
        "frames": frames,
        "orfs": [[option, [asdict(row) for row in find_orfs(sequence, **option)]] for option in options],
        "tm": [[setting, melting_record_for_sequence(sequence, MeltingConditions(**setting)).tm_celsius]
               for setting in conditions],
    }


def fixture(name, text):
    records, comments = read_fasta_text(text)
    gc = gc_windows_for_records(records, 9, 5)
    skew = skew_windows_for_records(records, 9, 5)
    return {
        "name": name,
        "text": text,
        "parsed": {"comments": comments, "records": [
            {"id": r.id, "description": r.description, "sequence": str(r.seq)} for r in records
        ]},
        "stats": [asdict(row) for row in analyze_records(records)],
        "windows": [asdict(a) | asdict(b) for a, b in zip(gc, skew, strict=True)],
        "results": [reference(str(r.seq)) for r in records],
    }


def main():
    rng = random.Random(20261122)
    random_fasta = "\n; preamble\n  # comment\n>empty\n>nested\nATGATGNNNTAAATGGC\n"
    random_fasta += ">iupac\naUrYSWKMBDHVN\n"
    for index in range(12):
        alphabet = "ACGT" if index % 2 else IUPACData.ambiguous_dna_letters
        sequence = "".join(rng.choices(alphabet, k=37 + index * 11))
        random_fasta += f">random-{index}\n{sequence[:30]}\n{sequence[30:]}\n"
    # Stress every possible ambiguous codon in every genetic code.
    codons = "".join("".join(codon) for codon in itertools.product(IUPACData.ambiguous_dna_letters, repeat=3))
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", category=BiopythonWarning)
        fixtures = [fixture(path.name, path.read_text(encoding="utf-8-sig"))
                    for path in sorted((ROOT / "data").glob("*.fasta"))]
        fixtures += [fixture("seeded and edge cases", random_fasta), fixture("all IUPAC codons", f">codons\n{codons}\n")]
    target = ROOT / "web/tests/fixtures/parity.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(fixtures, separators=(",", ":")) + "\n", encoding="utf-8", newline="\n")

    codes = {key: {"name": table.names[0], "starts": table.start_codons,
                   "stops": table.stop_codons, "amino": table.forward_table}
             for key, table in sorted(CodonTable.unambiguous_dna_by_id.items())}
    data = {"codes": codes, "iupac": IUPACData.ambiguous_dna_values,
            "complement": IUPACData.ambiguous_dna_complement, "stacks": DNA_NN3}
    (ROOT / "web/reference.mjs").write_text(
        "// Generated by scripts/export_parity_fixtures.py from Biopython (NCBI tables and DNA_NN3).\n"
        + "".join(f"export const {key} = {json.dumps(value, separators=(',', ':'))};\n"
                  for key, value in data.items()),
        encoding="utf-8", newline="\n",
    )


if __name__ == "__main__":
    main()
